// 2. Таблица умножения на 5 (от 1 до 10)
// ---------------------------------------------------------
console.log("\n--- Таблица умножения на 5 ---");
for (let i = 1; i <= 10; i++) {
    // Умножаем 5 на текущее значение счетчика i
    console.log("5 x " + i + " = " + (5 * i));
}


// ---------------------------------------------------------
// 3. Поиск максимума из трех чисел с помощью условий
// ---------------------------------------------------------
let num1 = 15;
let num2 = 42;
let num3 = 8;
let max;

// Последовательно сравниваем числа между собой
if (num1 >= num2 && num1 >= num3) {
    max = num1;
} else if (num2 >= num1 && num2 >= num3) {
    max = num2;
} else {
    max = num3;
}

console.log("\nДаны числа: " + num1 + ", " + num2 + ", " + num3);
console.log("Максимальное из них: " + max);


// ---------------------------------------------------------
// 4. Вычисление факториала числа N с помощью цикла
// ---------------------------------------------------------
let N = 5; // Вы можете изменить это число для проверки (например, на 6 или 7)
let factorial = 1; // Начальное значение, так как умножение на 0 даст 0

for (let i = 1; i <= N; i++) {
    factorial = factorial * i; // На каждой итерации умножаем текущий результат на i
    // Можно записать короче: factorial *= i;
}

console.log("\nФакториал числа " + N + " равен: " + factorial);
