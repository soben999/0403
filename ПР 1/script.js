// ---------------------------------------------------------
// 1. Калькулятор возраста
// ---------------------------------------------------------
// Запрашиваем год рождения у пользователя через всплывающее окно
let birthYearInput = prompt("Введите ваш год рождения (например, 2005):");

// Преобразуем введенную строку в целое число
let birthYear = parseInt(birthYearInput);
// Получаем текущий год динамически
let currentYear = new Date().getFullYear();

// Проверяем, что пользователь ввел именно число, а не отменил ввод или не ввел текст
if (!isNaN(birthYear)) {
    let age = currentYear - birthYear;
    console.log("Ваш возраст: " + age + " лет.");
} else {
    console.log("Ошибка: введите корректный год рождения (число).");
}


